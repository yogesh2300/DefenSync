def _assert_no_blank_labels(html: str, case: unittest.TestCase) -> None:
    for label in REQUIRED_LABELS:
        match = re.search(
            rf">{re.escape(label)}</td><td[^>]*>(.*?)</td>",
            html,
            flags=re.IGNORECASE | re.DOTALL,
        )
        case.assertIsNotNone(match, f"missing label {label!r}")
        value = re.sub(r"<[^>]+>", "", match.group(1)).strip()
        case.assertTrue(value, f"blank value for {label!r}")
        case.assertNotIn("Execute previous nodes", value)


def _render_template_with_fields(template: str, fields: dict[str, str]) -> str:
    """Substitute email_fields expressions for offline validation (not an n8n runtime)."""

    def replacer(match: re.Match[str]) -> str:
        expr = match.group(1)
        key_match = re.search(r"email_fields\.(\w+)", expr)
        if key_match:
            return fields.get(key_match.group(1), "N/A")
        return "N/A"

    return re.sub(r"\{\{([^}]+)\}\}", replacer, template)


