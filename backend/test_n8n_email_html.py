class PasteTemplateTests(unittest.TestCase):
    def test_template_file_has_dynamic_expressions_not_preview_placeholders(self):
        text = TEMPLATE_PATH.read_text(encoding="utf-8")
        body = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
        self.assertNotIn("[Execute previous nodes for preview]", body)
        self.assertIn("{{$json.body.notification.email_fields.severity", body)
        self.assertIn("$json.body.notification.email_fields.actor", body)
        self.assertIn("$json.body.notification.email_fields.incident_id", body)
        self.assertIn("$json.body.notification.email_fields.recommended_action", body)
        self.assertGreater(body.count("{{$json.body"), 10)

    def test_render_paste_template_with_demo_fields(self):
        payload = build_collection_payload(
            event_id="evt-1",
            source_type="CLOUD",
            collection_id="col-demo-001",
            sequence_number=1,
            completed_at=NOW,
            outcome="cloud_success",
            security_demo=DEMO_RAW,
            recipient_emails=["yogeshsalve2334@gmail.com"],
        )
        template = TEMPLATE_PATH.read_text(encoding="utf-8")
        # Strip HTML comment block before render check.
        template = re.sub(r"<!--.*?-->", "", template, flags=re.DOTALL)
        rendered = _render_template_with_fields(template, payload["notification"]["email_fields"])
        self.assertIn("High", rendered)
        self.assertIn("CLOUD", rendered)
        self.assertIn("70/100", rendered)
        self.assertIn("demo-suspicious-user", rendered)
        self.assertIn("Suspicious Cloud Privilege Change", rendered)
        self.assertIn("evt-1", rendered)
        self.assertNotIn("{{", rendered)
        self.assertNotIn("Execute previous nodes", rendered)


