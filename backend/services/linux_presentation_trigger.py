"""Linux presentation demo trigger for a server owner listed in PRESENTATION_TELEMETRY_EMAILS.

Only a successful manual collection started by the server's owner counts towards the interval
(backend.services.presentation_trigger). When the interval is reached this stores one marked
event and one marked alert, keyed by the collection run, which "Run correlation" turns into an
incident and n8n notification like any other telemetry. Nothing is generated for failed or
offline collections, scheduled or admin collections, or any read. Genuine Linux rows are never
read or changed, and the record is not LIVE_LINUX, so the Linux model never sees it.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.core.environments import LINUX
from backend.core.logging import get_logger
from backend.core.timestamps import collection_now
from backend.database import crud
from backend.database.models import DATA_SCOPE_PRIVATE, PRESENTATION_DATA_ORIGIN, Alert, CollectionRun, Server, User
from backend.database.scope import is_admin
from backend.services import presentation_trigger
from backend.services.cloud.presentation_telemetry import (
    DETECTION_TYPE,
    GENERATOR,
    KIND_TRIGGER,
    MARKER,
    RECORD_ORIGIN,
    TIMESTAMP_SOURCE,
    allowed_emails,
)

logger = get_logger(__name__)

NOTE = "Generated by DefenSync for a presentation. Not collected from the Linux server."
EVENT_TYPE = "Sudo Command"
RISK_SCORE = 80
SEVERITY = "high"
RECOMMENDATION = (
    "Advisory only: this is a presentation record. Review the incident workflow and notification; "
    "DefenSync does not change the server."
)
_EVENT_ID_NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "defensync:linux-presentation-trigger")


def _owner(server: Server) -> str | None:
    return server.owner_id or server.created_by


def enabled(user: User | None, server: Server, settings: Any = None) -> bool:
    """Only the server owner's own manual collection, and only when that owner's email is listed."""
    if user is None or is_admin(user) or not _owner(server) or user.id != _owner(server):
        return False
    emails = allowed_emails(settings)
    return bool(emails) and (user.email or "").strip().lower() in emails


def record_linux_presentation_trigger(session: Session, *, user: User | None, server: Server, run: CollectionRun) -> dict[str, Any] | None:
    """Advance the demo interval for one completed manual collection. Never raises; None when not enabled."""
    if run.status != "completed" or not enabled(user, server):
        return None
    try:
        return _record(session, user=user, server=server, run=run)
    except Exception as exc:  # noqa: BLE001 - a presentation problem must never fail the real collection
        session.rollback()
        logger.error("Linux presentation trigger not stored for server %s run %s: %s", server.id, run.id, type(exc).__name__)
        return None


def _record(session: Session, *, user: User, server: Server, run: CollectionRun) -> dict[str, Any]:
    now = collection_now()
    owner_id = _owner(server)
    progress = presentation_trigger.advance(
        session, owner_id=owner_id, account_id=server.account_id, environment=LINUX, run_id=run.id, now=now,
    )
    inserted = alert_created = False
    event_id = None
    if progress.triggered:
        payload = _payload(user=user, server=server, run=run, owner_id=owner_id, when=now)
        event_id = payload["event_id"]
        if not crud.get_existing_event_hashes(session, [payload["hash"]]):
            crud.insert_events_with_hash(session, [payload])
            inserted = True
        if session.scalar(select(Alert.id).where(Alert.event_id == event_id)) is None:
            session.add(_alert(payload, server=server, owner_id=owner_id))
            alert_created = True
    session.commit()
    logger.info(
        "Linux presentation trigger for server %s run %s: counted=%s trigger_inserted=%s alert_created=%s",
        server.id, run.id, progress.counted, inserted, alert_created,
    )
    return {
        "trigger_inserted": inserted,
        "trigger_event_id": event_id,
        "alert_created": alert_created,
        "trigger": presentation_trigger.state_view(progress.state, LINUX),
    }


def _hash(server: Server, owner_id: str | None, run: CollectionRun) -> str:
    scope = presentation_trigger.scope_key(owner_id, server.account_id)
    material = "|".join(("DEFENSYNC_PRESENTATION_V1", scope, f"server:{server.id}", f"run:{run.id}"))
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def _payload(*, user: User, server: Server, run: CollectionRun, owner_id: str | None, when) -> dict[str, Any]:
    actor = (user.email or user.username).strip().lower()
    event_hash = _hash(server, owner_id, run)
    metadata = {
        "presentation_generated": True,
        "generator": GENERATOR,
        "presentation_kind": KIND_TRIGGER,
        "record_origin": RECORD_ORIGIN,
        "record_kind": "PRESENTATION_RECORD",
        "note": NOTE,
        "collection_run_id": run.id,
        "timestamp_source": TIMESTAMP_SOURCE,
        "event_time_utc": when.isoformat(),
    }
    raw = {"presentation_generated": True, "generator": GENERATOR, "actor": actor, "note": NOTE}
    return {
        "event_id": str(uuid.uuid5(_EVENT_ID_NAMESPACE, event_hash)),
        "hash": event_hash,
        "timestamp": when,
        "collection_timestamp": when,
        "timestamp_source": TIMESTAMP_SOURCE,
        "category": "privilege",
        "severity": SEVERITY,
        "risk_score": RISK_SCORE,
        "raw_log": json.dumps(raw, sort_keys=True),
        "normalized_data": json.dumps(metadata, sort_keys=True),
        "source_type": LINUX,
        "provider": None,
        "data_origin": PRESENTATION_DATA_ORIGIN,
        "data_scope": DATA_SCOPE_PRIVATE,
        "dataset_name": None,
        "owner_id": owner_id,
        "account_id": server.account_id,
        "server_id": server.id,
        "parser_status": "PARSED",
        "hostname": (server.server_name or server.host)[:100],
        "username": actor[:100],
        "actor_id": actor[:255],
        "source_ip": None,
        "event_type": EVENT_TYPE,
        "message": f"Simulated privileged sudo command to root by {actor} on {server.server_name} {MARKER}",
    }


def _alert(payload: dict[str, Any], *, server: Server, owner_id: str | None) -> Alert:
    return Alert(
        event_id=payload["event_id"],
        server_id=server.id,
        owner_id=owner_id,
        account_id=server.account_id,
        title=f"{EVENT_TYPE} on {payload['hostname']} {MARKER}",
        message=payload["message"],
        severity=SEVERITY,
        risk_score=RISK_SCORE,
        risk_level="high",
        detection_type=DETECTION_TYPE,
        explanation=f"Simulated privileged command by {payload['actor_id']}. {NOTE}",
        recommendation=RECOMMENDATION,
        risk_factors=json.dumps(["privileged_command", "presentation_generated"]),
        event_timestamp=payload["timestamp"],
    )
