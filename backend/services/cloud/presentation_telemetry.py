def allowed_emails(settings: Any = None) -> frozenset[str]:
    raw = getattr(settings or get_settings(), "PRESENTATION_TELEMETRY_EMAILS", "") or ""
    return frozenset(item.strip().lower() for item in raw.split(",") if item.strip())


def presentation_enabled(user: User, source: CloudSource, settings: Any = None) -> bool:
    """Only for the source owner's own collection, and only when that owner's email is listed."""
    emails = allowed_emails(settings)
    if not emails or not source.owner_id or user.id != source.owner_id:
        return False
    return (user.email or "").strip().lower() in emails


def record_presentation_telemetry(
    session: Session,
    *,
    user: User,
    source: CloudSource,
    run: CloudCollectionRun,
    storage_tz: tzinfo = timezone.utc,
    settings: Any = None,
) -> dict[str, Any] | None:
    """Store the presentation records for one successful run. Never raises; None when not enabled."""
    if not presentation_enabled(user, source, settings):
        return None
    try:
        return _record(session, user=user, source=source, run=run, storage_tz=storage_tz)
    except Exception as exc:  # noqa: BLE001 - a presentation problem must never fail the real collection
        session.rollback()
        logger.error("Presentation telemetry not stored for cloud source %s run %s: %s", source.id, run.id, type(exc).__name__)
        return None


def security_demo_from_event(event: Any) -> dict[str, Any] | None:
    """Build the n8n/email privilege-demo block from a stored presentation trigger event."""
    try:
        metadata = json.loads(getattr(event, "normalized_data", None) or "{}")
    except (TypeError, ValueError):
        return None
    if not metadata.get("presentation_generated") or metadata.get("presentation_kind") != KIND_TRIGGER:
        return None
    risk = int(getattr(event, "risk_score", 0) or 0)
    when = getattr(event, "timestamp", None)
    collection_id = metadata.get("collection_id") or metadata.get("collection_run_id")
    return {
        "simulated": True,
        "demo_label": DEMO_LABEL,
        "title": DEMO_TITLE,
        "system_name": SYSTEM_NAME,
        "environment": CLOUD,
        "operation": metadata.get("original_operation") or getattr(event, "operation", None) or DEMO_OPERATION,
        "operation_result": "Failed",
        "initiating_user": DEMO_ACTOR,
        "target_resource": DEMO_RESOURCE_GROUP,
        "event_timestamp": when.isoformat() if isinstance(when, datetime) else when,
        "risk_score": risk,
        "risk_level": risk_level_from_score(risk),
        "event_type": getattr(event, "event_type", None),
        "collection_id": collection_id,
        "recommended_action": RECOMMENDATION,
        "email_subject": DEMO_EMAIL_SUBJECT,
        "data_origin": PRESENTATION_DATA_ORIGIN,
        "note": NOTE,
    }


def cloud_demo_every_success(settings: Any = None) -> bool:
    return bool(getattr(settings or get_settings(), "CLOUD_DEMO_EVERY_SUCCESS", True))


def cloud_demo_n8n_every_success(settings: Any = None) -> bool:
    return bool(getattr(settings or get_settings(), "CLOUD_DEMO_N8N_EVERY_SUCCESS", True))


def _record(session: Session, *, user: User, source: CloudSource, run: CloudCollectionRun, storage_tz: tzinfo) -> dict[str, Any]:
    collected_at = collection_now()
    settings = get_settings()
    actor = (user.email or user.username).strip().lower()
    anchor = _aware(source.created_at, storage_tz) or collected_at
    setup = [
        _setup_payload(step, source=source, actor=actor, when=anchor - timedelta(minutes=step.minutes_before_source),
                       collected_at=collected_at, kind=KIND_SETUP, key=f"setup:{step.key}")
        for step in SETUP_STEPS
    ]
    every_success = cloud_demo_every_success(settings)
    progress = presentation_trigger.advance(
        session, owner_id=source.owner_id, account_id=source.account_id, environment=CLOUD, run_id=run.id, now=collected_at,
    )
    # Every-success mode: one DEMO privilege incident per successful run (idempotent via run-keyed hash).
    # Interval mode: only when presentation_trigger completes its 1–3 collection window.
    should_trigger = True if every_success else bool(progress.triggered)
    payloads = list(setup)
    trigger = None
    if should_trigger:
        trigger = _trigger_payload(source=source, run=run, when=collected_at, collected_at=collected_at)
        payloads.append(trigger)
    existing = crud.get_existing_event_hashes(session, [item["hash"] for item in payloads])
    fresh = [item for item in payloads if item["hash"] not in existing]
    if fresh:
        crud.insert_events_with_hash(session, fresh)
    alert_created = _ensure_alert(session, trigger, source=source) if trigger is not None else False
    session.commit()
    security_demo = _security_demo_from_payload(trigger, run=run) if trigger is not None else None
    summary = {
        "setup_inserted": sum(1 for item in fresh if item is not trigger),
        "trigger_inserted": trigger is not None and any(item is trigger for item in fresh),
        "trigger_event_id": trigger["event_id"] if trigger is not None else None,
        "alert_created": alert_created,
        "demo_incident_created": bool(trigger is not None and (alert_created or not any(item is trigger for item in fresh))),
        "trigger_risk_score": trigger["risk_score"] if trigger is not None else None,
        "security_demo": security_demo,
        "every_success": every_success,
        "trigger": {
            **presentation_trigger.state_view(progress.state, CLOUD),
            "policy": "every_success" if every_success else "interval_1_to_3",
            "triggered_this_run": should_trigger,
        },
    }
    # demo_incident_created: True when this run has a demo event (new or already stored for this run).
    if trigger is not None:
        summary["demo_incident_created"] = True
    logger.info(
        "Presentation telemetry for cloud source %s run %s: setup_inserted=%d counted=%s trigger_inserted=%s alert_created=%s risk=%s policy=%s",
        source.id, run.id, summary["setup_inserted"], progress.counted, summary["trigger_inserted"], alert_created,
        summary["trigger_risk_score"], "every_success" if every_success else "interval",
    )
    return summary


def _ensure_alert(session: Session, trigger: dict[str, Any], *, source: CloudSource) -> bool:
    if session.scalar(select(Alert.id).where(Alert.event_id == trigger["event_id"])) is not None:
        return False
    risk = int(trigger["risk_score"])
    level = risk_level_from_score(risk)
    session.add(Alert(
        event_id=trigger["event_id"],
        server_id=None,
        owner_id=source.owner_id,
        account_id=source.account_id,
        title=f"{DEMO_LABEL}: {DEMO_TITLE} {MARKER}",
        message=trigger["message"],
        severity=level,
        risk_score=risk,
        risk_level=level,
        detection_type=DETECTION_TYPE,
        explanation=(
            f"{DEMO_LABEL}: Unauthorized attempt to assign an Owner role via {DEMO_OPERATION} by {DEMO_ACTOR} "
            f"on {DEMO_RESOURCE_GROUP} (operation Failed). {NOTE}"
        ),
        recommendation=RECOMMENDATION,
        risk_factors=json.dumps([
            "privileged_role_assignment",
            "owner_role",
            "failed_operation",
            "presentation_generated",
            "simulated_demo",
            DEMO_LABEL,
        ]),
        event_timestamp=trigger["timestamp"],
    ))
    return True


def _setup_payload(
    step: Step,
    *,
    source: CloudSource,
    actor: str,
    when: datetime,
    collected_at: datetime,
    kind: str,
    key: str,
) -> dict[str, Any]:
    event_hash = _hash(source, key)
    event_type = classify_azure_event({}, operation=step.operation, sign_in=step.sign_in, sign_in_failed=False if step.sign_in else None)
    metadata = {
        "presentation_generated": True,
        "generator": GENERATOR,
        "presentation_kind": kind,
        "presentation_step": step.key,
        "record_origin": RECORD_ORIGIN,
        "azure_record": False,
        "azure_table": None,
        "note": NOTE,
        "original_operation": step.operation,
        "cloud_source_id": source.id,
        "collection_run_id": None,
        "collection_id": None,
        "timestamp_source": TIMESTAMP_SOURCE,
        "event_time_utc": when.astimezone(timezone.utc).isoformat(),
        "first_collection_time_utc": collected_at.astimezone(timezone.utc).isoformat(),
    }
    raw = {"presentation_generated": True, "generator": GENERATOR, "operation": step.operation, "actor": actor, "note": NOTE}
    return {
        "event_id": str(uuid.uuid5(_EVENT_ID_NAMESPACE, event_hash)),
        "hash": event_hash,
        "timestamp": when,
        "collection_timestamp": collected_at,
        "timestamp_source": TIMESTAMP_SOURCE,
        "category": "cloud",
        "severity": step.severity,
        "risk_score": step.risk_score,
        "raw_log": json.dumps(raw, sort_keys=True),
        "normalized_data": json.dumps(metadata, sort_keys=True),
        "source_type": CLOUD,
        "provider": PROVIDER,
        "data_origin": PRESENTATION_DATA_ORIGIN,
        "data_scope": DATA_SCOPE_PRIVATE,
        "dataset_name": None,
        "owner_id": source.owner_id,
        "account_id": source.account_id,
        "server_id": None,
        "parser_status": "PARSED",
        "hostname": step.hostname,
        "username": actor[:100],
        "actor_id": actor[:255],
        "source_ip": None,
        "event_type": event_type,
        "message": f"{step.text} by {actor} {MARKER}",
        "resource_id": f"presentation/{step.key}",
        "resource_type": step.resource_type,
        "operation": step.operation,
    }


def _trigger_payload(
    *,
    source: CloudSource,
    run: CloudCollectionRun,
    when: datetime,
    collected_at: datetime,
) -> dict[str, Any]:
    """Failed Owner roleAssignments/write via azure_normalizer, then presentation re-stamp."""
    key = f"run:{run.id}"
    event_hash = _hash(source, key)
    resource_id = (
        f"/subscriptions/{_PRESENTATION_SUB}/resourceGroups/{DEMO_RESOURCE_GROUP}/"
        f"providers/Microsoft.Authorization/roleAssignments/demo-owner-ra"
    )
    synthetic = {
        "TenantId": _PRESENTATION_TENANT,
        "TimeGenerated": when.astimezone(timezone.utc).isoformat().replace("+00:00", "Z"),
        "OperationNameValue": DEMO_OPERATION,
        "OperationName": "Create role assignment",
        "Caller": DEMO_ACTOR,
        "CallerIpAddress": "203.0.113.50",
        "CategoryValue": "Administrative",
        "ActivityStatusValue": "Failed",
        "ActivitySubstatusValue": "Unauthorized attempt to assign Owner role",
        "CorrelationId": f"presentation-corr-{run.id}",
        "EventDataId": f"presentation-trigger-{run.id}",
        "SubscriptionId": _PRESENTATION_SUB,
        "ResourceGroup": DEMO_RESOURCE_GROUP,
        "_ResourceId": resource_id,
        "ResourceProviderValue": "Microsoft.Authorization",
        "Claims": {
            "http://schemas.xmlsoap.org/ws/2005/05/identity/claims/upn": DEMO_ACTOR,
            "http://schemas.microsoft.com/identity/claims/objectidentifier": "00000000-0000-0000-0000-demosuspicious01",
            "appid": "00000000-0000-0000-0000-presentationapp",
        },
        "Authorization": {"action": DEMO_OPERATION, "scope": resource_id},
        "Level": "Error",
    }
    normalized = normalize_record(
        AZURE_ACTIVITY,
        synthetic,
        owner_id=source.owner_id or "",
        account_id=source.account_id,
        collected_at=collected_at,
        collection_id=run.collection_id or run.id,
    )
    metadata = json.loads(normalized["normalized_data"])
    metadata.update({
        "presentation_generated": True,
        "generator": GENERATOR,
        "presentation_kind": KIND_TRIGGER,
        "presentation_step": "owner-assignment-failed",
        "record_origin": RECORD_ORIGIN,
        "azure_record": False,
        "azure_table": None,
        "note": NOTE,
        "cloud_source_id": source.id,
        "collection_run_id": run.id,
        "collection_id": run.collection_id,
        "timestamp_source": TIMESTAMP_SOURCE,
        "event_time_utc": when.astimezone(timezone.utc).isoformat(),
        "first_collection_time_utc": collected_at.astimezone(timezone.utc).isoformat(),
        "demo_actor": DEMO_ACTOR,
        "demo_resource_group": DEMO_RESOURCE_GROUP,
        "demo_scenario": "unauthorized_owner_role_assignment",
        "normalized_via": "azure_normalizer",
        "scoring": "live_failed_activity",
    })
    message = (
        f"{DEMO_LABEL}: {DEMO_TITLE} — {DEMO_OPERATION} Failed by {DEMO_ACTOR} on {DEMO_RESOURCE_GROUP}: "
        f"unauthorized attempt to assign Owner role {MARKER}"
    )
    raw = {
        "presentation_generated": True,
        "generator": GENERATOR,
        "operation": DEMO_OPERATION,
        "actor": DEMO_ACTOR,
        "resource_group": DEMO_RESOURCE_GROUP,
        "status": "Failed",
        "role": "Owner",
        "note": NOTE,
        "synthetic_azure_activity": True,
    }
    return {
        **normalized,
        "event_id": str(uuid.uuid5(_EVENT_ID_NAMESPACE, event_hash)),
        "hash": event_hash,
        "timestamp": when,
        "collection_timestamp": collected_at,
        "timestamp_source": TIMESTAMP_SOURCE,
        "data_origin": PRESENTATION_DATA_ORIGIN,
        "data_scope": DATA_SCOPE_PRIVATE,
        "provider": PROVIDER,
        "source_type": CLOUD,
        "owner_id": source.owner_id,
        "account_id": source.account_id,
        "server_id": None,
        "hostname": DEMO_RESOURCE_GROUP,
        "username": DEMO_ACTOR[:100],
        "actor_id": DEMO_ACTOR[:255],
        "message": message,
        "raw_log": json.dumps(raw, sort_keys=True),
        "normalized_data": json.dumps(metadata, sort_keys=True),
        "operation": DEMO_OPERATION,
    }


def _security_demo_from_payload(trigger: dict[str, Any], *, run: CloudCollectionRun | None = None) -> dict[str, Any]:
    risk = int(trigger["risk_score"])
    when = trigger.get("timestamp")
    collection_id = None
    if run is not None:
        collection_id = run.collection_id or run.id
    else:
        try:
            collection_id = json.loads(trigger.get("normalized_data") or "{}").get("collection_id")
        except (TypeError, ValueError):
            collection_id = None
    return {
        "simulated": True,
        "demo_label": DEMO_LABEL,
        "title": DEMO_TITLE,
        "system_name": SYSTEM_NAME,
        "environment": CLOUD,
        "operation": DEMO_OPERATION,
        "operation_result": "Failed",
        "initiating_user": DEMO_ACTOR,
        "target_resource": DEMO_RESOURCE_GROUP,
        "event_timestamp": when.isoformat() if isinstance(when, datetime) else when,
        "risk_score": risk,
        "risk_level": risk_level_from_score(risk),
        "event_type": trigger.get("event_type"),
        "collection_id": collection_id,
        "recommended_action": RECOMMENDATION,
        "email_subject": DEMO_EMAIL_SUBJECT,
        "data_origin": PRESENTATION_DATA_ORIGIN,
        "note": NOTE,
    }


def _hash(source: CloudSource, key: str) -> str:
    """Namespaced like the Azure hash but under its own scheme, so it can never equal a real record's."""
    scope = f"account:{source.account_id}" if source.account_id else f"owner:{source.owner_id}"
    material = "|".join(("DEFENSYNC_PRESENTATION_V1", scope, f"source:{source.id}", key))
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def _aware(value: datetime | None, storage_tz: tzinfo) -> datetime | None:
    if value is None:
        return None
    return value if value.tzinfo else value.replace(tzinfo=storage_tz)
