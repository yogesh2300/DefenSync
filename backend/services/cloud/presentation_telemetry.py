"""Presentation telemetry for cloud sources owned by a user listed in PRESENTATION_TELEMETRY_EMAILS.

Nothing here is retrieved from Azure. Every row is stored with data_origin=PRESENTATION_SIMULATED,
normalized_data record_origin=PRESENTATION_GENERATED and presentation_generated=true, its message
ends with "[presentation record]", and it is private to the cloud source's tenant. Real Azure rows,
their dedup hashes and the collection run counters are never read or changed.

After a successful collection run started by the source owner this stores, idempotently:
- once per source, the onboarding setup sequence (sign-in, app registration, service principal,
  client secret added, role assignment, workspace and diagnostic configuration, elevated access),
  timed just before the source was added to DefenSync;
- when CLOUD_DEMO_EVERY_SUCCESS is true (default), every successful collection creates one Failed
  Owner roleAssignments/write attempt for demo-suspicious-user on demo-resource-group (keyed by
  run id, idempotent on retry). When false, the legacy 1–3 collection interval
  (presentation_trigger) is used instead. The trigger row is produced by feeding a synthetic
  Azure Activity-shaped record through azure_normalizer (live failed→70 scoring), then re-stamping
  presentation markers so it never looks like live AZURE_LOG_ANALYTICS telemetry.

Operations are described, never reproduced: no secret, token or credential value is stored.
"""

